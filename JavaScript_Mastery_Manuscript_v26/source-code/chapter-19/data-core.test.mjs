import test from 'node:test';
import assert from 'node:assert/strict';
import {createDataset,queryDataset,summarize,windowRange,debounce,measure} from './data-core.mjs';
const data=createDataset(100);
test('dataset size',()=>assert.equal(data.length,100));
test('deterministic IDs',()=>assert.deepEqual(data.slice(0,2).map(x=>x.id),[1,2]));
test('empty dataset',()=>assert.deepEqual(createDataset(0),[]));
test('negative count rejected',()=>assert.throws(()=>createDataset(-1),RangeError));
test('too large rejected',()=>assert.throws(()=>createDataset(100001),RangeError));
test('search matches',()=>assert.equal(queryDataset(data,{search:'000001'}).length,1));
test('category filter',()=>assert.equal(queryDataset(data,{category:'Books'}).length,20));
test('sort descending',()=>{const a=queryDataset(data,{sort:'price-desc'});assert.ok(a[0].price>=a.at(-1).price)});
test('original unchanged',()=>{const ids=data.map(x=>x.id);queryDataset(data,{sort:'score-desc'});assert.deepEqual(data.map(x=>x.id),ids)});
test('invalid sort',()=>assert.throws(()=>queryDataset(data,{sort:'oops'}),RangeError));
test('summary count',()=>assert.equal(summarize(data).count,100));
test('summary total',()=>assert.equal(summarize(data).total,data.reduce((s,x)=>s+x.price,0)));
test('empty summary',()=>assert.deepEqual(summarize([]),{count:0,total:0,average:0,min:0,max:0}));
test('range top',()=>assert.deepEqual(windowRange(100,0,40,400,5),{start:0,end:15}));
test('range bottom clamped',()=>assert.deepEqual(windowRange(100,4000,40,400,5),{start:95,end:100}));
test('range empty',()=>assert.deepEqual(windowRange(0,0,40,400),{start:0,end:0}));
test('invalid row height',()=>assert.throws(()=>windowRange(100,0,0,400),RangeError));
test('measure returns value',()=>assert.equal(measure('sum',()=>2+3).value,5));
test('debounce validates',()=>assert.throws(()=>debounce(null),TypeError));
test('debounce coalesces',async()=>{let value=0;const f=debounce(n=>value=n,10);f(1);f(2);await new Promise(r=>setTimeout(r,30));assert.equal(value,2)});
