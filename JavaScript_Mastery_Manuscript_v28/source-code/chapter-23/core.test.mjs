import test from 'node:test';import assert from 'node:assert/strict';
import {makeTrips,normalizeQuery,filterTrips,sortTrips,windowRange,memoizeLast} from './core.mjs';
const data=makeTrips(120);
test('dataset count',()=>assert.equal(data.length,120));
test('unique IDs',()=>assert.equal(new Set(data.map(x=>x.id)).size,120));
test('reject invalid count',()=>assert.throws(()=>makeTrips(-1),RangeError));
test('empty dataset',()=>assert.deepEqual(makeTrips(0),[]));
test('query normalization',()=>assert.equal(normalizeQuery('  DHAKA '),'dhaka'));
test('search matches destination',()=>assert.ok(filterTrips(data,{query:'sylhet'}).every(x=>x.destination==='Sylhet')));
test('filter destination',()=>assert.equal(filterTrips(data,{destination:'Dhaka'}).length,20));
test('filter price',()=>assert.ok(filterTrips(data,{maxPrice:4000}).every(x=>x.price<=4000)));
test('combined filter',()=>assert.ok(filterTrips(data,{destination:'Sylhet',maxPrice:4000}).every(x=>x.destination==='Sylhet'&&x.price<=4000)));
test('reject negative max price',()=>assert.throws(()=>filterTrips(data,{maxPrice:-1}),RangeError));
test('sort ascending',()=>{const a=sortTrips(data);assert.ok(a.every((v,i)=>i===0||a[i-1].price<=v.price))});
test('sort descending',()=>{const a=sortTrips(data,'price-desc');assert.ok(a.every((v,i)=>i===0||a[i-1].price>=v.price))});
test('sort does not mutate',()=>{const before=data.map(x=>x.id);sortTrips(data);assert.deepEqual(data.map(x=>x.id),before)});
test('reject invalid sort',()=>assert.throws(()=>sortTrips(data,'unknown'),RangeError));
test('window start and end',()=>assert.deepEqual(windowRange({scrollTop:0,rowHeight:50,viewportHeight:200,total:100,overscan:2}),{start:0,end:6,offset:0,totalHeight:5000}));
test('window near end clamps',()=>{const r=windowRange({scrollTop:4950,rowHeight:50,viewportHeight:200,total:100,overscan:2});assert.equal(r.end,100)});
test('window zero rows',()=>assert.equal(windowRange({total:0}).end,0));
test('reject invalid row height',()=>assert.throws(()=>windowRange({rowHeight:0}),RangeError));
test('memoize last',()=>{let n=0;const f=memoizeLast(x=>{n++;return x*2});assert.equal(f(3),6);assert.equal(f(3),6);assert.equal(n,1);assert.equal(f(4),8);assert.equal(n,2)});
