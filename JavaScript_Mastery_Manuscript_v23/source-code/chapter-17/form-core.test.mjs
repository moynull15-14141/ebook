import test from 'node:test';import assert from 'node:assert/strict';
import {normalizeSpace,validateName,validateEmail,validatePhone,validatePassword,validateRegistration,escapeHTML,maskEmail} from './form-core.mjs';
test('space normalization',()=>assert.equal(normalizeSpace(' A   B '),'A B'));
test('Bangla name',()=>assert.equal(validateName('মোঃ রহমান').ok,true));
test('Unicode Bengali name',()=>assert.equal(validateName('রহমান').ok,true));
test('Latin name',()=>assert.equal(validateName('Amina Rahman').ok,true));
test('name rejects HTML',()=>assert.equal(validateName('<script>').ok,false));
test('name rejects empty',()=>assert.equal(validateName(' ').ok,false));
test('email lowercases',()=>assert.equal(validateEmail(' USER@EXAMPLE.COM ').value,'user@example.com'));
test('email rejects malformed',()=>assert.equal(validateEmail('bad@').ok,false));
test('email rejects oversized',()=>assert.equal(validateEmail('a'.repeat(255)+'@example.com').ok,false));
test('phone accepts BD international format',()=>assert.equal(validatePhone('+880 1712-345678').value,'+8801712345678'));
test('phone rejects letters',()=>assert.equal(validatePhone('123ABC').ok,false));
test('phone rejects too short',()=>assert.equal(validatePhone('123').ok,false));
test('password accepts long mixed case',()=>assert.equal(validatePassword('SecurePass1234').ok,true));
test('password rejects short',()=>assert.equal(validatePassword('Abc123').ok,false));
test('password rejects weak',()=>assert.equal(validatePassword('abcdefghijklmnop').ok,false));
test('form validates all fields',()=>assert.equal(validateRegistration({name:'Amina',email:'amina@example.com',phone:'+8801712345678',password:'SecurePass1234',consent:true}).ok,true));
test('form rejects missing consent',()=>assert.ok(validateRegistration({name:'Amina',email:'amina@example.com',phone:'+8801712345678',password:'SecurePass1234',consent:false}).errors.consent));
test('form returns field errors',()=>assert.ok(validateRegistration({}).errors.email));
test('escapeHTML encodes markup',()=>assert.equal(escapeHTML('<b>"&'), '&lt;b&gt;&quot;&amp;'));
test('maskEmail hides local part',()=>assert.equal(maskEmail('amina@example.com'),'a***@example.com'));
