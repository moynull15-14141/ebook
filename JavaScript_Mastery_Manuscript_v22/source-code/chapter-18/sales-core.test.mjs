import test from 'node:test';import assert from 'node:assert/strict';
import {sampleOrders,normalizeOrder,prepareOrders,paidOnly,sumRevenue,totalUnits,groupByCategory,rankCategories,filterOrders,pipe,summarize} from './sales-core.mjs';
const data=prepareOrders(sampleOrders);
test('prepares six orders',()=>assert.equal(data.length,6));
test('normalizes string quantities',()=>assert.equal(normalizeOrder({...sampleOrders[0],quantity:'2'}).total,1800));
test('rejects invalid quantity',()=>assert.throws(()=>normalizeOrder({...sampleOrders[0],quantity:0}),RangeError));
test('rejects negative price',()=>assert.throws(()=>normalizeOrder({...sampleOrders[0],unitPrice:-1}),RangeError));
test('rejects bad status',()=>assert.throws(()=>normalizeOrder({...sampleOrders[0],status:'mystery'}),TypeError));
test('rejects non-array input',()=>assert.throws(()=>prepareOrders({}),TypeError));
test('rejects duplicate ids',()=>assert.throws(()=>prepareOrders([sampleOrders[0],sampleOrders[0]]),/Duplicate/));
test('paid filter excludes refund',()=>assert.equal(paidOnly(data).length,5));
test('revenue excludes refund',()=>assert.equal(sumRevenue(data),14200));
test('units excludes refund',()=>assert.equal(totalUnits(data),8));
test('groups categories',()=>assert.equal(groupByCategory(data).Books.revenue,2900));
test('ranking descending',()=>assert.equal(rankCategories(data)[0].category,'Courses'));
test('filters by category',()=>assert.equal(filterOrders(data,{category:'Books'}).length,3));
test('filters by status',()=>assert.equal(filterOrders(data,{status:'refunded'}).length,1));
test('case insensitive search',()=>assert.equal(filterOrders(data,{query:'advanced'}).length,1));
test('pipe composes left to right',()=>assert.equal(pipe(x=>x+2,x=>x*3)(4),18));
test('summarize matches filters',()=>assert.equal(summarize(sampleOrders,{category:'Books'}).revenue,2900));
test('does not mutate inputs',()=>{const before=JSON.stringify(sampleOrders);summarize(sampleOrders);assert.equal(JSON.stringify(sampleOrders),before)});
test('empty report is safe',()=>assert.deepEqual(summarize([]),{orders:[],revenue:0,units:0,ranking:[]}));
