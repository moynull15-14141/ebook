const assert = require('node:assert/strict');
const T = require('./text-tools');
let passed = 0;
const test = (name, fn) => { fn(); passed++; console.log('PASS', name); };
test('empty word count', () => assert.equal(T.wordCount(''), 0));
test('mixed-language words', () => assert.equal(T.wordCount('বাংলা JavaScript 2026'), 3));
test('trim and NFC normalization', () => assert.equal(T.normalize('  cafe\u0301  '), 'café'));
test('unicode code points', () => assert.equal(T.characterCount('🙂'), 1));
test('graphemes available', () => assert.ok(T.graphemeCount('👨‍👩‍👧‍👦') >= 1));
test('slug latin', () => assert.equal(T.slugify(' Hello, JavaScript! '), 'hello-javascript'));
test('slug bangla', () => assert.equal(T.slugify('বাংলা লেখা'), 'বাংলা-লেখা'));
test('excerpt short', () => assert.equal(T.excerpt('Hello', 10), 'Hello'));
test('excerpt truncate', () => assert.equal(T.excerpt('Hello world', 5), 'Hello…'));
test('excerpt rejects zero', () => assert.throws(() => T.excerpt('Hi', 0), RangeError));
test('frequency counts', () => assert.deepEqual(T.frequency('JS js JS'), [['js', 3]]));
test('search insensitive', () => assert.deepEqual(T.search('JavaScript javascript', 'JAVASCRIPT').map(x=>x.index), [0,11]));
test('search empty query', () => assert.deepEqual(T.search('abc', ''), []));
test('search non-overlap', () => assert.deepEqual(T.search('aaaa', 'aa').map(x=>x.index), [0,2]));
test('analyze summary', () => assert.equal(T.analyze('Hello hello').frequency[0][1], 2));
console.log(`All ${passed} tests passed`);
